    h2("（六）偏序轨迹对齐")
    p("出题图常常有汇合和分支，期望执行不是唯一的一条全序。若把图强行排成一个序列再和轨迹比编辑距离，并发节点对调顺序会被误报成乱序。对齐算法先承认偏序，再做序列比对。")
    p("第一步，对每个节点分别搜索后继，得到 happens-before 可达关系，最坏 O(V·(V+E))；规格先后约束再补充匹配节点对。第二步，Kahn 过程按观测位置反复排序就绪节点，当前最坏有 O(V² log V) 排序成本。第三步，用编辑距离动态规划比对期望与观测序列，时间和矩阵空间 O(n·m)。这里分别陈述实际实现的各项成本。")
    p("编辑距离的递推和经典的 Needleman–Wunsch 相同，但替换代价设为很大的常数，只有标识相同才允许零代价对角前进。动态规划因此只在两条序列之间做缺位匹配，不会把两个不同标识换成彼此。缺一个期望节点，标成缺失。多一次观测执行，标成意外执行。第四步回看匹配对：若后一个节点按 happens-before 必须先于前一个节点，却在轨迹里更早出现，就把这一对改标为乱序。没有先后关系的两个节点对调顺序，仍然保持匹配。")
    p("期望序列长度记为 n，观测序列长度记为 m。替换代价写成 subst。标识相同是 0，否则是 1000000。对角步因此几乎不会被选中，除非两个位置是同一个节点。")
    code("dp[i][0] = i\ndp[0][j] = j\nsubst = 0 if expected[i-1] == observed[j-1] else 1000000\ndp[i][j] = min(dp[i-1][j] + 1, dp[i][j-1] + 1, dp[i-1][j-1] + subst)")
    p("第一项删掉一个期望节点，标成缺失。第二项表示观测里多了一次执行，标成意外执行。第三项只在标识相同时代价为 0。回溯从右下角走到左上角，标识相同并且代价没有增加时优先走对角。以期望序列 Schedule、HTTP、IF、Email 和观测序列 Schedule、HTTP、Email 为例：前两个标识零代价对齐，Email 与 Email 对齐，IF 只能走删除，代价为 1，标成缺失。把 IF 替换成 Email 的那一步代价是一百万，动态规划不会选它。这个常数就是对齐算法的优化：用一次 O(n·m) 的编辑距离完成匹配，同时不把不同节点当成可以互相替换的近似。")
    p("展示用的是一条线性扩展，不是所有交错的枚举，也不是 Petri 网过程挖掘。算法登记和返回结果里都写了这个限制。代价是并发匹配是近似的；收益是比对可以在 O(n·m) 内完成，并且不会把合法的并发对调报成缺陷。")

