def script():
    from pathlib import Path
    lines = Path(__file__).with_name("06-演示视频脚本.md").read_text(encoding="utf-8").splitlines()
    b = []; i = 0
    while i < len(lines):
        line = lines[i].strip()
        if line.startswith("### "): b.append(("h2", line[4:]))
        elif line.startswith("## "): b.append(("h1", line[3:]))
        elif line.startswith("|"):
            rows = []
            while i < len(lines) and lines[i].strip().startswith("|"):
                row = [c.strip() for c in lines[i].strip().strip("|").split("|")]
                if not all(set(c) <= set("-:") for c in row): rows.append(row)
                i += 1
            if rows: b.append(("table", rows[0], rows[1:]))
            continue
        elif line and not line.startswith(("# ", "- ")): b.append(("p", line))
        i += 1
    return b
